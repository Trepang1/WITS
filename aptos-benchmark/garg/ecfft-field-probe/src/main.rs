//! Arithmetic prerequisite only: NOT a Garg proof or gas result.
use ark_ff::{Field, Fp256, MontBackend, MontConfig, UniformRand, Zero, One};
use ark_poly::{univariate::DensePolynomial, DenseUVPolynomial, Polynomial};
use ecfft::{ec::{GoodCurve, Point, ShortWeierstrassCurve, Isogeny}, find_curve::find_curve, utils::RationalMap, FFTree};
use rand::{rngs::StdRng, SeedableRng};
use serde_json::json;
use std::{fs, time::Instant};

#[derive(MontConfig)]
#[modulus = "7237005577332262213973186563042994240857116359379907606001950938285454250989"]
#[generator = "2"]
pub struct ScalarFieldConfig;
type F = Fp256<MontBackend<ScalarFieldConfig, 4>>;

// Use the actual order-two subgroup generated by g at EACH stage. The
// dependency's fixed GoodCurve chain did not halve order in this field near
// its final levels. Velu's maps below are the same formulas used by its
// ShortWeierstrassCurve::two_isogenies, without a cubic root search.
fn kernel_chain(mut g: Point<ShortWeierstrassCurve<F>>, log_n: u32) -> Vec<RationalMap<F>> {
    let mut maps = vec![];
    for remaining in (1..=log_n).rev() {
        let mut kernel = g;
        for _ in 1..remaining { kernel += kernel; }
        assert!(!kernel.is_zero() && (kernel + kernel).is_zero());
        let domain = g.curve.unwrap();
        let x0 = kernel.x;
        let t = F::from(3u8)*x0.square() + domain.a;
        let codomain = ShortWeierstrassCurve::new(domain.a-F::from(5u8)*t, domain.b-F::from(7u8)*x0*t);
        let r = RationalMap::new(&[t, -x0, F::one()], &[-x0, F::one()]);
        let h = RationalMap::new(&[x0.square()-t, -x0.double(), F::one()], &[x0.square(), -x0.double(), F::one()]);
        let iso = Isogeny::new(domain, codomain, r, RationalMap::zero(), h);
        assert!(iso.map(&kernel).is_zero());
        g = iso.map(&g);
        if remaining > 1 {
            assert!(!g.is_zero());
            assert_eq!(g.y.square(), g.x*g.x*g.x + codomain.a*g.x + codomain.b);
            let mut order = g;
            for _ in 1..remaining-1 { order += order; }
            assert!(!order.is_zero() && (order + order).is_zero());
        } else { assert!(g.is_zero()); }
        maps.push(iso.r);
    }
    maps
}

fn main() {
    let dir = std::env::args().nth(1).expect("output directory");
    fs::create_dir_all(&dir).unwrap();
    let n: usize = std::env::args().nth(2).unwrap_or_else(|| "256".into()).parse().unwrap();
    assert!(n.is_power_of_two());
    let mut rng = StdRng::seed_from_u64(20261012);
    let now = Instant::now();
    let (order_log, generator) = find_curve::<F>(&mut rng, n.ilog2());
    let find_ms = now.elapsed().as_secs_f64() * 1000.;
    let curve = generator.curve.unwrap();
    let (a, b) = match curve { GoodCurve::Odd { a, b } => (a, b), _ => unreachable!() };
    let mut g = generator;
    for _ in n.ilog2()..order_log { g += g; }
    let mut order_check = g;
    for _ in 0..n.ilog2()-1 { order_check += order_check; }
    assert!(!order_check.is_zero());
    order_check += order_check;
    assert!(order_check.is_zero());
    let now = Instant::now();
    let (offset, leaves) = loop {
        let x = F::rand(&mut rng);
        if let Some(y) = (x * (x.square() + a*x + b.square())).sqrt() {
            let offset = Point::new(x, y, curve);
            let mut current = offset;
            let mut xs = Vec::with_capacity(n);
            for _ in 0..n { xs.push(current.x); current += g; }
            let mut sorted = xs.clone(); sorted.sort(); sorted.dedup();
            if sorted.len() == n && !xs.iter().any(|x| x.is_zero()) { break (offset, xs); }
        }
    };
    let shift = a / F::from(3u8);
    let short = ShortWeierstrassCurve::new(b.square()-a*shift, F::from(2u8)*shift*shift*shift-b.square()*shift);
    let short_g = Point::new(g.x+shift, g.y, short);
    let maps = kernel_chain(short_g, n.ilog2());
    let leaves: Vec<_> = leaves.into_iter().map(|x| x+shift).collect();
    let tree = FFTree::new(leaves.clone(), maps);
    let tree_ms = now.elapsed().as_secs_f64() * 1000.;
    let poly = DensePolynomial::<F>::rand(n-1, &mut rng);
    let now = Instant::now();
    let actual = tree.enter(&poly);
    let enter_ms = now.elapsed().as_secs_f64() * 1000.;
    let expected: Vec<_> = leaves.iter().map(|x| poly.evaluate(x)).collect();
    assert_eq!(actual, expected);
    let now = Instant::now();
    assert_eq!(tree.exit(&actual), poly.coeffs);
    let exit_ms = now.elapsed().as_secs_f64() * 1000.;
    let result = json!({"field":"Ed25519 scalar field", "domain_size":n,
        "find_curve_ms":find_ms,"tree_ms":tree_ms,"enter_ms":enter_ms,"exit_ms":exit_ms,
        "naive_evaluations_match":true,"roundtrip_matches":true,"garg_verifier_implemented":false,
        "curve_a":a.to_string(),"curve_b_squared":b.square().to_string(),
        "generator_x":g.x.to_string(),"generator_y":g.y.to_string(),
        "coset_x":offset.x.to_string(),"coset_y":offset.y.to_string(),
        "subgroup_order":n,"find_curve_order_log":order_log,
        "isogeny_chain":"kernel-selected Velu maps on short Weierstrass coordinates",
        "domain_coordinate_shift":shift.to_string()});
    fs::write(format!("{dir}/ecfft-field-probe.json"), serde_json::to_vec_pretty(&result).unwrap()).unwrap();
    println!("{}", serde_json::to_string_pretty(&result).unwrap());
}
